function listItems(items = []) {
  return items.map((item) => `- ${item}`).join("\n");
}

function renderUnderstandingForThumbnail(u) {
  if (!u) return "";
  const props = Array.isArray(u.thumbnailProps) && u.thumbnailProps.length
    ? u.thumbnailProps.map((p) => `「${p}」`).join(" / ")
    : "(指定なし)";
  return `## この記事の理解 (サムネに必ず反映)

このサムネは、タイトルだけで描いてはいけません。次を反映してください。

- 記事テーマ: ${u.articleTheme || "(未設定)"}
- 読者の疑問: ${u.readerQuestion || "(未設定)"}
- 読者が判断したい点: ${u.readerDecisionPoint || "(未設定)"}
- ひまりの反応 (記事内容を読んだ後): ${u.himariReaction || "(未設定)"}
- らぼまるの役割 (整理係): ${u.labomaruRole || "(未設定)"}
- サムネで使う道具の候補: ${props}
- サムネ構図の方向性: ${u.thumbnailCompositionIdea || "(未設定)"}

サムネ思想 (絶対):
- ひまり・らぼまるが記事内容を理解し、その内容に対して感情・表情・道具・構図で自由に反応する
- テンプレ化・置物化・無難化は禁止
- 安全化を理由に、感情・面白さ・自由さを削らない
- 文字を減らすこと自体を目的にしない (情報量は維持)
- 大きな文字は2つまで / 補助文字は2つまで
- 実在ロゴ・実機写真コピーは使わない

衣装・小道具は「変えることを基本」(★恒久方針・assets/characters/character-sheet.md 準拠):
- **記事テーマから連想される衣装・小道具・シチュエーションを必ず1つ選び、この生成プロンプトに明記すること。** 標準衣装のまま出すのは「ひねり不要なとき（続報で前回と揃える等）」の例外だけ。
- **★フォールバック（標準衣装まま禁止）**: どの装い例にも当てはまらないテーマでも「標準衣装のまま」で出さない。記事の名詞から連想する小道具＋装いを最低1点必ず入れ、その根拠を slide_plan のサムネ節に1行記録する。
- 認識アンカーは不変(ひまり=金髪サイドテール・青い瞳・顔立ち・頭身 / らぼまる=白い卵型ボディ・黄緑アンテナ・黒い丸目・胸のオレンジのハートボタン)。変えるのは服・上着・アクセ・持ち物・背景であってキャラの同一性ではない。
- らぼまるは素体なので服は着せず、帽子・小道具・持ち物・背景でテーマを表現する。
- テーマ→装い例: AIモデル/性能/研究=白衣・ゴーグル・試験管 / 料金・プラン・サブスク=ビジネスカジュアル・電卓・料金表 / 制限・上限の緩和/開放・撤廃・無料化・延長系=解放感の装い(ストップウォッチ/ゲージの小道具・腕まくり・走り出しそうな動き) / 発表会=ジャケット・ステージ / 季節ネタ=季節の装い / セキュリティ=探偵/ガード風・虫めがね / 時間・締切・カレンダー系=カレンダー・大きな時計・砂時計。
- 露出の多い/扇情的な衣装は不可(この一線だけは不変)。
- **手は自然に描く**: 開いた手・軽く添える手を優先し、手は小さめ・遠め、動作する手は片手だけにする。強い把持、両手の別動作、指を組む・数えるポーズ、手のクローズアップを避ける。手を隠すためだけの後ろ手・机の陰・フレームアウトは使わず、テーマ衣装・小道具配置・姿勢と視線・背景の演出密度を保つ。
- スライド8枚側も演出ブロックの衣装方針に従う。中立解説系で理由を明記した場合だけ標準衣装を許可し、手の安全指定を理由に標準衣装へ退避しない。

`;
}

